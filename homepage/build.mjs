// Builds the homepage served at "/" from homepage/home.html (the same file the design preview uses).
//
//   node homepage/build.mjs
//
// Writes src/app/home-html.ts (the page as a string; src/app/route.ts serves it with the live listings filled in).
// Run it after editing home.html, and commit the result. The page's other files are served from public/:
// car-art.js (body-style illustrations), cutouts.js and cutouts/ (made by homepage/make_cutouts.py).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
let html = readFileSync(join(here, "home.html"), "utf8");

const swap = (from, to) => {
  if (!html.includes(from)) throw new Error(`home.html no longer contains: ${from}`);
  html = html.replace(from, to);
};

// What Google shows: the title leads with what people search for, the description earns the click.
const title = "Used Cars Up to 40% Below Market in Metairie | Kami Motors";
const description =
  "See today's cash prices: quality used cars in Metairie, LA, up to 40% below market. $0 dealer fees, $0 doc fee, financing available. Kami Motors (KMG AUTO LLC).";
// What shows when someone shares the link (Facebook, texts)
const shareTitle = "Drive More, Pay Less | Kami Motors, Metairie LA";
// Business details for Google: the trading name, the registered LLC, and how to reach the lot
const business = {
  "@context": "https://schema.org",
  "@type": "AutoDealer",
  name: "Kami Motors",
  legalName: "KMG AUTO LLC",
  alternateName: "KMG AUTO",
  slogan: "Drive More, Pay Less",
  url: "https://www.kamimotorsgroup.com/",
  telephone: "+1-504-294-3995",
  address: { "@type": "PostalAddress", addressLocality: "Metairie", addressRegion: "LA", postalCode: "70001", addressCountry: "US" },
  areaServed: "New Orleans metro area",
  openingHours: "Mo-Sa 09:00-19:00",
};
const attr = (t) => t.replace(/&/g, "&amp;").replace(/"/g, "&quot;");

// preview-only bits out, the site's own title and sharing details in
swap("<title>Kami Motors Homepage</title>\n", "");
swap('<meta name="claude:viewport-fit-sides" content="cover">\n', "");
html = html.replace(/<div class="note mono">[^<]*<\/div>\n/, "");
// the server fills in the listings (see src/app/route.ts); static files are served from the site root
swap('<script src="listings.js"></script>', "<script>/*KM_INVENTORY*/</script>");
swap('<script src="car-art.js"></script>', '<script src="/car-art.js"></script>');
swap('<script src="cutouts.js"></script>', '<script src="/cutouts.js"></script>');

const head = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${attr(description)}">
<link rel="canonical" href="https://www.kamimotorsgroup.com/">
<meta property="og:title" content="${shareTitle}">
<meta property="og:description" content="${attr(description)}">
<meta property="og:type" content="website">
<meta property="og:url" content="https://www.kamimotorsgroup.com/">
<meta property="og:site_name" content="Kami Motors">
<link rel="icon" href="/favicon.ico">
<script type="application/ld+json">${JSON.stringify(business)}</script>
`;
html = head + html + "\n</html>\n";

writeFileSync(
  join(root, "src/app/home-html.ts"),
  "// Generated by homepage/build.mjs from homepage/home.html. Do not edit by hand.\n" +
    `export const HOME_HTML = ${JSON.stringify(html)};\n`
);
console.log(`homepage built: ${(html.length / 1024).toFixed(0)} KB`);
